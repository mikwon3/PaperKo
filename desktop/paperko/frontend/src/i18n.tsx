export function tr(lang: UILang, ko: string): string {
  return lang === 'en' ? (EN[ko] ?? ko) : ko
}

const LangContext = createContext<UILang>('ko')

export function useT(): { lang: UILang; t: (ko: string) => string } {
  const lang = useContext(LangContext)
  return { lang, t: (ko: string) => tr(lang, ko) }
}

export function LangProvider({ lang, children }: { lang: UILang; children: ReactNode }) {
  return <LangContext.Provider value={lang}>{children}</LangContext.Provider>
}
